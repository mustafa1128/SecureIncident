-- Supabase SQL Editor-də işlət.
create table if not exists public.incidents (
  id bigint generated by default as identity primary key,
  title text not null,
  department text not null check (department in ('Admin','HR','IT Support')),
  priority text not null check (priority in ('Kritik','Orta','Aşağı')),
  status text not null default 'Açıq' check (status in ('Açıq','Araşdırılır','Həll olunub')),
  description text not null,
  created_at timestamptz not null default now()
);

-- YALNIZ müəllimə demo göstərmək üçün açıq demo siyasəti:
-- Bu siyasət giriş etməyən hər kəsə oxuma/yazma imkanı verə bilər.
-- Real və ya həssas məlumat istifadə etmə. Real layihədə Supabase Auth + RLS
-- və istifadəçi/rol yoxlamaları qurulmalıdır.
alter table public.incidents enable row level security;
create policy "demo read incidents" on public.incidents for select to anon using (true);
create policy "demo insert incidents" on public.incidents for insert to anon with check (true);
create policy "demo update incidents" on public.incidents for update to anon using (true) with check (true);
